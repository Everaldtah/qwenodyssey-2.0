//! Coordinator events. The TypeScript coordinator was a typed `EventEmitter`;
//! here every subscriber gets its own unbounded tokio channel, so a slow
//! consumer (the TUI redraws at 10 fps) never loses a streamed delta the way a
//! lagging `broadcast` receiver would, and the coordinator never blocks on a
//! subscriber. Dropping a receiver unsubscribes it.

use std::sync::{Arc, Mutex};

use serde::Serialize;
use tokio::sync::mpsc::{unbounded_channel, UnboundedReceiver, UnboundedSender};

use crate::coordinator::{Subtask, SubtaskStatus};
use crate::exec::PlanComplexity;
use crate::swarm::{RosterEntry, SwarmArtifacts, SwarmRun, WorkerResult};

/// "plan": decomposition finished, roster known.
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub struct PlanEvent {
    pub task: String,
    pub subtasks: Vec<Subtask>,
    pub roster: Vec<RosterEntry>,
    /// Which model produced the plan ("(supplied)" for --divide, "(fallback)"
    /// when planning failed, "(none)" when every agent failed preflight).
    pub planned_by: Option<String>,
    /// Human-readable diagnostic when planning degraded (e.g. a lead timed out).
    pub note: Option<String>,
    /// Planner's complexity judgment for the project.
    pub complexity: Option<PlanComplexity>,
    /// Execution backend label when agents can run commands ("bare metal" / "daytona sandbox").
    pub exec: Option<String>,
}

/// "wave": a parallel batch is about to run.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct WaveEvent {
    pub index: usize,
    pub subtask_ids: Vec<String>,
}

/// "assign": a subtask was placed on a worker/pane.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct AssignEvent {
    pub pane: usize,
    pub subtask_id: String,
    pub title: String,
    pub worker_label: String,
    pub model: String,
}

/// "delta": streamed token(s) from a worker (also shell commands + output tails).
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct DeltaEvent {
    pub pane: usize,
    pub subtask_id: String,
    pub delta: String,
}

/// "status": a subtask changed state.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct StatusEvent {
    pub pane: usize,
    pub subtask_id: String,
    pub status: SubtaskStatus,
    pub ms: Option<u64>,
    pub error: Option<String>,
}

/// "execCmd": an agent ran a command on the execution backend.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct ExecCmdEvent {
    pub pane: usize,
    pub subtask_id: String,
    pub command: String,
    pub ok: bool,
}

/// One worker's key/endpoint health check.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct PreflightResult {
    pub pane: usize,
    pub label: String,
    pub model: String,
    pub backend: String,
    pub ok: bool,
    pub detail: Option<String>,
    pub ms: u64,
}

/// Everything a coordinated run reports, in emission order:
/// preflight → planner → plan → (wave → assign/status/delta/execCmd/result)* →
/// synth/synthDelta → artifacts → done.
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(tag = "event", content = "data", rename_all = "camelCase")]
pub enum SwarmEvent {
    /// About to health-check the roster's keys.
    PreflightStart { count: usize },
    /// One worker's key/endpoint checked (ok/broken).
    Preflight(PreflightResult),
    /// Health-check finished.
    PreflightDone { ok: usize, broken: usize },
    /// A decompose attempt started on this model.
    Planner { model: String },
    Plan(PlanEvent),
    Wave(WaveEvent),
    Assign(AssignEvent),
    Delta(DeltaEvent),
    Status(StatusEvent),
    /// A subtask finished (full text; the coordinated fields are filled).
    Result(WorkerResult),
    ExecCmd(ExecCmdEvent),
    /// Synthesis started on this model.
    Synth { model: String },
    /// Streamed token(s) from the synthesizer.
    SynthDelta { delta: String },
    /// Files generated by the execution backend.
    Artifacts(SwarmArtifacts),
    /// Everything finished.
    Done(SwarmRun),
}

/// Lossless fan-out of [`SwarmEvent`]s to any number of subscribers.
#[derive(Clone, Default)]
pub struct SwarmEvents {
    subscribers: Arc<Mutex<Vec<UnboundedSender<SwarmEvent>>>>,
}

impl SwarmEvents {
    pub fn new() -> Self {
        Self::default()
    }

    /// A new receiver that sees every event emitted from now on.
    pub fn subscribe(&self) -> UnboundedReceiver<SwarmEvent> {
        let (tx, rx) = unbounded_channel();
        self.lock().push(tx);
        rx
    }

    /// Send `event` to every live subscriber (closed ones are pruned).
    pub fn emit(&self, event: SwarmEvent) {
        let mut subs = self.lock();
        subs.retain(|s| !s.is_closed());
        let Some((last, rest)) = subs.split_last() else {
            return;
        };
        for s in rest {
            let _ = s.send(event.clone());
        }
        let _ = last.send(event);
    }

    /// Number of live subscribers.
    pub fn subscriber_count(&self) -> usize {
        let mut subs = self.lock();
        subs.retain(|s| !s.is_closed());
        subs.len()
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, Vec<UnboundedSender<SwarmEvent>>> {
        self.subscribers.lock().unwrap_or_else(|e| e.into_inner())
    }
}

impl std::fmt::Debug for SwarmEvents {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SwarmEvents").field("subscribers", &self.subscriber_count()).finish()
    }
}
