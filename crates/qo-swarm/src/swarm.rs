//! Agent swarm: fan a single task out to MANY frontier models at the SAME TIME,
//! each running on its own backend + API key (NVIDIA NIM, OpenRouter, and—when
//! asked—local Ollama/LM Studio). Two shapes:
//!
//!  - ensemble: every worker answers the SAME task in parallel, then their
//!    answers are synthesized into one best result (breadth + consensus).
//!  - divide:   a list of independent subtasks is sharded across the workers,
//!    one per worker (round-robin), all running concurrently (parallelism).
//!
//! The roster is built from the configured PRIMARY (when it's a cloud model) plus
//! every cloud ref in `model.fallback_models` whose API key is present — so the
//! swarm automatically uses all the frontier keys you already have configured.

use std::collections::HashSet;
use std::fmt;
use std::sync::LazyLock;
use std::time::Instant;

use futures::future::join_all;
use qo_core::{CancellationToken, Message, ModelOptions, Provider, SharedProvider};
use regex::Regex;
use serde::Serialize;

use crate::compat;
use crate::env::SwarmEnv;

/// Reasoning/thinking models need heat — at temp 0 they loop. One classifier for
/// the whole harness: the family profile in `qo_core::model_profile`.
pub use crate::compat::is_reasoning_model;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum WorkerKind {
    Nvidia,
    #[serde(rename = "openrouter")]
    OpenRouter,
    #[default]
    Ollama,
    #[serde(rename = "lmstudio")]
    LmStudio,
}

impl WorkerKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            WorkerKind::Nvidia => "nvidia",
            WorkerKind::OpenRouter => "openrouter",
            WorkerKind::Ollama => "ollama",
            WorkerKind::LmStudio => "lmstudio",
        }
    }

    /// Map a `Provider::name()` onto a worker kind (unknown backends display as ollama,
    /// matching the TS roster fallback).
    pub fn from_provider_name(name: &str) -> Self {
        match name {
            "nvidia" => WorkerKind::Nvidia,
            "openrouter" => WorkerKind::OpenRouter,
            "lmstudio" => WorkerKind::LmStudio,
            _ => WorkerKind::Ollama,
        }
    }
}

impl fmt::Display for WorkerKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// One swarm member: a model on its own backend + key.
#[derive(Clone)]
pub struct SwarmWorker {
    /// Canonical ref, e.g. "openrouter:moonshotai/kimi-k2.6" (bare tag for Ollama).
    pub model_ref: String,
    pub kind: WorkerKind,
    pub model: String,
    /// Short display name.
    pub label: String,
    pub provider: SharedProvider,
}

impl fmt::Debug for SwarmWorker {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("SwarmWorker")
            .field("model_ref", &self.model_ref)
            .field("kind", &self.kind)
            .field("model", &self.model)
            .field("label", &self.label)
            .finish()
    }
}

/// Display-only view of a worker.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct RosterEntry {
    pub label: String,
    pub model: String,
    pub backend: String,
}

/// One worker's answer. Coordinated runs also fill `id` / `title` / `depends_on`
/// (the TS `CoordinatedResult extends WorkerResult`).
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub struct WorkerResult {
    pub label: String,
    pub model: String,
    pub backend: WorkerKind,
    /// The subtask this worker handled (divide/coordinated mode); the shared task otherwise.
    pub task: String,
    pub ok: bool,
    pub text: String,
    pub error: Option<String>,
    pub ms: u64,
    pub prompt_tokens: Option<u64>,
    pub completion_tokens: Option<u64>,
    /// Coordinated subtask id.
    pub id: Option<String>,
    /// Coordinated subtask title.
    pub title: Option<String>,
    /// Coordinated subtask dependencies.
    pub depends_on: Vec<String>,
}

/// Files generated by the execution backend during a run.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct SwarmArtifacts {
    /// Where the files live, e.g. "bare metal: C:\\Users\\me" or "daytona sandbox sb-1".
    pub location: String,
    /// Paths of files the agents created/modified during the run.
    pub files: Vec<String>,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum SwarmMode {
    #[default]
    Ensemble,
    Divide,
}

impl SwarmMode {
    pub fn as_str(&self) -> &'static str {
        match self {
            SwarmMode::Ensemble => "ensemble",
            SwarmMode::Divide => "divide",
        }
    }
}

#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub struct SwarmRun {
    pub mode: SwarmMode,
    pub results: Vec<WorkerResult>,
    /// Final synthesized answer, when synthesis ran.
    pub synthesis: Option<String>,
    pub synthesized_by: Option<String>,
    /// Files generated by the execution backend (when agents ran commands).
    pub artifacts: Option<SwarmArtifacts>,
}

#[derive(Clone, Debug, Default)]
pub struct SwarmOptions {
    /// Cap the number of workers spun up.
    pub max_workers: Option<usize>,
    /// Also include local refs (bare Ollama tags / lmstudio:*) from the fallback list.
    pub include_local: bool,
    /// Per-worker output budget.
    pub max_tokens: Option<u32>,
    /// Esc / Ctrl-C: aborts every in-flight worker request.
    pub cancel: Option<CancellationToken>,
}

/// A fallback/primary ref → backend kind + model id (`nvidia:`, `openrouter:`,
/// `lmstudio:` prefixes; anything else is a bare Ollama tag).
pub fn parse_ref(r: &str) -> (WorkerKind, String) {
    for (prefix, kind) in [
        ("nvidia:", WorkerKind::Nvidia),
        ("openrouter:", WorkerKind::OpenRouter),
        ("lmstudio:", WorkerKind::LmStudio),
    ] {
        if let Some(model) = r.strip_prefix(prefix) {
            return (kind, model.to_string());
        }
    }
    (WorkerKind::Ollama, r.to_string())
}

/// Short label for display (drop the org/ prefix).
pub fn short_label(model: &str) -> String {
    match model.rfind('/') {
        Some(i) => model[i + 1..].to_string(),
        None => model.to_string(),
    }
}

/// Build the swarm roster from config: the primary (if it's a cloud backend) plus
/// every cloud ref in the fallback chain whose API key is available. Cloud refs
/// without a key are skipped; local refs are included only when `include_local`.
pub fn frontier_workers(env: &SwarmEnv, opts: &SwarmOptions) -> Vec<SwarmWorker> {
    let have_nvidia = env.have_nvidia;
    let have_openrouter = env.have_openrouter;

    let mut refs: Vec<String> = Vec::new();
    // Primary, when it is itself a cloud model.
    let model = &env.primary_model;
    if env.primary_backend == "nvidia" {
        refs.push(format!("nvidia:{model}"));
    } else if env.primary_backend == "openrouter" {
        refs.push(format!("openrouter:{model}"));
    }
    // Fallback chain.
    for r in &env.fallback_models {
        let t = r.trim();
        if !t.is_empty() {
            refs.push(t.to_string());
        }
    }

    let mut seen: HashSet<String> = HashSet::new();
    let mut workers: Vec<SwarmWorker> = Vec::new();
    for r in refs {
        let (kind, model) = parse_ref(&r);
        let canonical = format!("{}:{}", kind.as_str(), model).to_lowercase();
        if seen.contains(&canonical) {
            continue;
        }
        // Cloud needs a key.
        if kind == WorkerKind::Nvidia && !have_nvidia {
            continue;
        }
        if kind == WorkerKind::OpenRouter && !have_openrouter {
            continue;
        }
        if matches!(kind, WorkerKind::Ollama | WorkerKind::LmStudio) && !opts.include_local {
            continue;
        }
        seen.insert(canonical);
        workers.push(SwarmWorker {
            model_ref: if kind == WorkerKind::Ollama { model.clone() } else { format!("{}:{}", kind.as_str(), model) },
            kind,
            label: short_label(&model),
            provider: env.factory.create(kind, &model),
            model,
        });
        if let Some(max) = opts.max_workers {
            if max > 0 && workers.len() >= max {
                break;
            }
        }
    }
    workers
}

/// Drives a roster of workers concurrently.
pub struct Swarm {
    workers: Vec<SwarmWorker>,
    opts: SwarmOptions,
    /// The `system.md` harness prompt, loaded once per swarm.
    system: String,
}

impl Swarm {
    pub fn new(workers: Vec<SwarmWorker>, opts: SwarmOptions) -> Self {
        Self::with_system(workers, opts, compat::system_prompt())
    }

    /// Same as [`Swarm::new`] with an explicit system prompt (tests / embedding).
    pub fn with_system(workers: Vec<SwarmWorker>, opts: SwarmOptions, system: impl Into<String>) -> Self {
        Self { workers, opts, system: system.into() }
    }

    pub fn size(&self) -> usize {
        self.workers.len()
    }

    pub fn roster(&self) -> Vec<RosterEntry> {
        self.workers
            .iter()
            .map(|w| RosterEntry { label: w.label.clone(), model: w.model.clone(), backend: w.kind.as_str().to_string() })
            .collect()
    }

    /// Same task to every worker, all at once.
    pub async fn ensemble(&self, task: &str, context: Option<&str>) -> SwarmRun {
        let prompt = with_context(task, context);
        let results = join_all(self.workers.iter().map(|w| self.ask(w, task, &prompt))).await;
        SwarmRun { mode: SwarmMode::Ensemble, results, ..Default::default() }
    }

    /// Shard independent subtasks across the workers (round-robin) and run them all
    /// concurrently. With more subtasks than workers, a worker handles several (still
    /// sequential within that worker, parallel across workers).
    pub async fn divide(&self, subtasks: &[String], context: Option<&str>) -> SwarmRun {
        let clean: Vec<&str> = subtasks.iter().map(|s| s.trim()).filter(|s| !s.is_empty()).collect();
        if self.workers.is_empty() {
            return SwarmRun { mode: SwarmMode::Divide, ..Default::default() };
        }
        // Group subtasks per worker by round-robin, then run each worker's group
        // sequentially while all workers run in parallel.
        let mut groups: Vec<Vec<&str>> = vec![Vec::new(); self.workers.len()];
        for (i, st) in clean.iter().enumerate() {
            groups[i % self.workers.len()].push(st);
        }
        let nested = join_all(self.workers.iter().zip(groups).filter(|(_, g)| !g.is_empty()).map(
            |(worker, tasks)| async move {
                let mut out = Vec::with_capacity(tasks.len());
                for st in tasks {
                    let prompt = with_context(st, context);
                    out.push(self.ask(worker, st, &prompt).await);
                }
                out
            },
        ))
        .await;
        SwarmRun { mode: SwarmMode::Divide, results: nested.into_iter().flatten().collect(), ..Default::default() }
    }

    /// One worker, one prompt. Never fails — failures become a failed result.
    async fn ask(&self, worker: &SwarmWorker, task: &str, prompt: &str) -> WorkerResult {
        let start = Instant::now();
        let messages = vec![Message::system(self.system.clone()), Message::user(prompt)];
        let opts = ModelOptions {
            temperature: Some(if is_reasoning_model(&worker.model) { 0.6 } else { 0.3 }),
            max_tokens: Some(self.opts.max_tokens.unwrap_or(1500)),
            cancel: self.opts.cancel.clone(),
            ..Default::default()
        };
        let base = WorkerResult {
            label: worker.label.clone(),
            model: worker.model.clone(),
            backend: worker.kind,
            task: task.to_string(),
            ..Default::default()
        };
        match worker.provider.generate(&messages, &opts).await {
            Ok(res) => WorkerResult {
                ok: true,
                text: strip_thinking(&res.text).trim().to_string(),
                ms: elapsed_ms(start),
                prompt_tokens: res.prompt_tokens,
                completion_tokens: res.completion_tokens,
                ..base
            },
            Err(err) => WorkerResult { ok: false, error: Some(format!("{err:#}")), ms: elapsed_ms(start), ..base },
        }
    }
}

fn with_context(task: &str, context: Option<&str>) -> String {
    match context {
        Some(c) if !c.is_empty() => format!("{task}\n\n--- Context ---\n{c}"),
        _ => task.to_string(),
    }
}

pub(crate) fn elapsed_ms(start: Instant) -> u64 {
    start.elapsed().as_millis() as u64
}

static THINK_BLOCK: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?is)<think(?:ing)?>.*?</think(?:ing)?>").expect("static regex"));
static THINK_CLOSE_ONLY: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?is)^.*?</think(?:ing)?>\s*(.*)$").expect("static regex"));

/// Drop a reasoning model's `<think>…</think>` block, keeping the final answer.
pub fn strip_thinking(text: &str) -> String {
    let closed = THINK_BLOCK.replace_all(text, "");
    // Close-only shape (templates pre-fill the opening tag).
    if let Some(c) = THINK_CLOSE_ONLY.captures(&closed) {
        return c.get(1).map(|m| m.as_str()).unwrap_or("").trim().to_string();
    }
    closed.trim().to_string()
}

/// Merge the workers' answers into one best result, using `lead` to judge and
/// combine. Falls back to concatenation if the synthesizer call fails.
pub async fn synthesize(
    lead: &dyn Provider,
    task: &str,
    run: &SwarmRun,
    max_tokens: u32,
    cancel: Option<&CancellationToken>,
) -> String {
    synthesize_with_system(lead, task, run, max_tokens, cancel, &compat::system_prompt()).await
}

/// [`synthesize`] with an explicit system prompt (tests / embedding).
pub async fn synthesize_with_system(
    lead: &dyn Provider,
    task: &str,
    run: &SwarmRun,
    max_tokens: u32,
    cancel: Option<&CancellationToken>,
    system: &str,
) -> String {
    let ok: Vec<&WorkerResult> = run.results.iter().filter(|r| r.ok && !r.text.is_empty()).collect();
    if ok.is_empty() {
        return "All swarm workers failed; no answer to synthesize.".to_string();
    }
    if ok.len() == 1 {
        return ok[0].text.clone();
    }

    let blocks = ok
        .iter()
        .enumerate()
        .map(|(i, r)| format!("### Answer {} — model: {}\n{}", i + 1, r.model, r.text))
        .collect::<Vec<_>>()
        .join("\n\n");
    let instruction = match run.mode {
        SwarmMode::Ensemble => "Multiple frontier models independently answered the SAME task. Combine their answers into a single, correct, complete best answer. Resolve disagreements by reasoning about which is right, keep the strongest ideas from each, and drop anything wrong or redundant. Do not mention that multiple models were involved.",
        SwarmMode::Divide => "Independent subtasks were each handled by a different model. Integrate their outputs into one coherent result that addresses the overall task. Keep each subtask's substance; reconcile overlaps.",
    };

    let messages = vec![
        Message::system(system),
        Message::user(format!(
            "TASK:\n{task}\n\n{instruction}\n\n{blocks}\n\n--- Now write the single best final answer below. ---"
        )),
    ];
    let opts = ModelOptions {
        temperature: Some(0.3),
        max_tokens: Some(max_tokens),
        cancel: cancel.cloned(),
        ..Default::default()
    };
    match lead.generate(&messages, &opts).await {
        Ok(res) => {
            let s = strip_thinking(&res.text);
            if s.is_empty() {
                blocks
            } else {
                s
            }
        }
        Err(_) => blocks,
    }
}
